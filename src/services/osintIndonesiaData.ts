function expandNumericRange(prefixBase: string, start: number, end: number, pad = 2): string[] {
  const out: string[] = [];
  for (let i = start; i <= end; i++) {
    out.push(`${prefixBase}${String(i).padStart(pad, '0')}`);
  }
  return out;
}

